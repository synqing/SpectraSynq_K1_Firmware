#!/usr/bin/env python3
"""Generate k1_pcm1808_resampler_coeffs.h (Kaiser windowed-sinc, L=4 M=15)."""

from __future__ import annotations

import math
from pathlib import Path

L = 4
M = 15
N = 256
FS = 192000.0
FC = 6000.0
BETA = 5.6
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "SPECTRASYNQ_K1_FIRMWARE" / "audio" / "k1_pcm1808_resampler_coeffs.h"


def i0(x: float) -> float:
    s = 1.0
    t = 1.0
    y = x / 2.0
    for k in range(1, 40):
        t *= (y * y) / (k * k)
        s += t
        if t < 1e-12:
            break
    return s


def kaiser(n: int, nn: int, beta: float) -> float:
    if nn == 1:
        return 1.0
    a = (nn - 1) / 2.0
    t = (n - a) / a
    if abs(t) > 1:
        return 0.0
    return i0(beta * math.sqrt(1 - t * t)) / i0(beta)


def main() -> None:
    h = []
    a = (N - 1) / 2.0
    for n in range(N):
        x = n - a
        sinc = (2 * FC / FS) if x == 0 else math.sin(2 * math.pi * FC * x / FS) / (math.pi * x)
        h.append(sinc * kaiser(n, N, BETA))
    s = sum(h)
    h = [v / s for v in h]
    phases: list[list[float]] = [[] for _ in range(L)]
    for i, v in enumerate(h):
        phases[i % L].append(v)
    taps = len(phases[0])
    lines = [
        "#pragma once",
        "// Auto-generated by tools/pcm1808/design_resampler.py (windowed-sinc Kaiser).",
        f"// L={L} M={M}, interpolated fs={FS:.0f} Hz, fc={FC:.0f} Hz, N={N}, {taps} taps/phase.",
        "// Do not edit by hand; regenerate the script.",
        "#include <stdint.h>",
        f"enum {{ K1_PCM_SRC_L = {L}, K1_PCM_SRC_M = {M}, K1_PCM_SRC_TAPS = {taps} }};",
        "static const float k1_pcm_src_phase[K1_PCM_SRC_L][K1_PCM_SRC_TAPS] = {",
    ]
    for p, ph in enumerate(phases):
        body = ", ".join(f"{v:.9e}f" for v in ph)
        comma = "," if p + 1 < L else ""
        lines.append(f"  {{ {body} }}{comma}")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} taps/phase={taps}")


if __name__ == "__main__":
    main()
